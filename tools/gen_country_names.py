#!/usr/bin/env python3
"""Generates the country names in the game's other languages
(crates/client/src/country_names.rs) from iso-codes' translations, for the
countries of crates/proto/src/countries.rs (English and Brazilian
Portuguese are there already).

Requirements: `pip install pycountry`.

    python3 tools/gen_country_names.py
"""
import gettext
import os
import re

import pycountry

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# The game's language code → iso-codes' locale. Spanish has a hand-made list
# too (crates/client/src/flags.rs), which wins.
LOCALES = {
    "es": "es",
    "pt-PT": "pt",
    "fr": "fr",
    "de": "de",
    "it": "it",
    "nl": "nl",
    "sv": "sv",
    "pl": "pl",
    "cs": "cs",
    "hu": "hu",
    "ro": "ro",
    "el": "el",
    "ru": "ru",
    "uk": "uk",
    "tr": "tr",
    "id": "id",
    "fil": "fil",
    "vi": "vi",
    "th": "th",
    "hi": "hi",
    "bn": "bn",
    "ar": "ar",
    "zh-CN": "zh_CN",
    "ja": "ja",
    "ko": "ko",
}


# Countries renamed in English since some translations were made: their
# older names find those translations.
ALIASES = {
    "TR": ["Turkey"],
    "CZ": ["Czech Republic"],
    "MK": ["Macedonia, Republic of", "Macedonia"],
    "SZ": ["Swaziland"],
    "CV": ["Cape Verde"],
}


def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main():
    src = open(os.path.join(ROOT, "crates/proto/src/countries.rs"), encoding="utf-8").read()
    rows = re.findall(r'\("([A-Z]{2})", "((?:[^"\\]|\\.)*)", "(?:[^"\\]|\\.)*"\)', src)
    out = [
        "// Generated by tools/gen_country_names.py: do not edit by hand.",
        "",
        "/// The countries' names in the game's other languages, in the order of",
        "/// `snook_legend_proto::COUNTRIES` (\"\": the same as in English).",
        "pub const NAMES: &[(&str, &[&str])] = &[",
    ]
    for code, locale in LOCALES.items():
        t = gettext.translation("iso3166-1", pycountry.LOCALES_DIR, languages=[locale])
        names = []
        for alpha2, en in rows:
            c = pycountry.countries.get(alpha_2=alpha2)
            candidates = [en]
            if c is not None:
                candidates += [getattr(c, "common_name", None), c.name]
            candidates += ALIASES.get(alpha2, [])
            # The first name the translation has (it may be the same as in
            # English); English if none.
            catalog = t._catalog
            name = next((catalog[x] for x in candidates if x and catalog.get(x)), en)
            names.append("" if name == en else name)
        out.append(f'    ("{code}", &[')
        out += [f'        "{esc(n)}",' for n in names]
        out.append("    ]),")
    out.append("];")
    path = os.path.join(ROOT, "crates/client/src/country_names.rs")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"{len(rows)} countries in {len(LOCALES)} languages")


if __name__ == "__main__":
    main()
