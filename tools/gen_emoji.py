#!/usr/bin/env python3
"""Generates the emoji atlas (crates/client/assets/emoji.png) and its table
(crates/client/assets/emoji.txt): the pictures the game draws for emoji in
text (the chats, status messages, notes, gift messages…), from Twemoji
(graphics CC-BY 4.0, like the reactions').

Requirements: `pip install pillow regex fonttools`, `rsvg-convert` (librsvg),
`pngquant`, and the Twemoji SVGs unpacked somewhere:

    npm pack @twemoji/svg@15.0.0 && tar xzf twemoji-svg-15.0.0.tgz
    python3 tools/gen_emoji.py package

Which emoji: every Twemoji picture (smileys, people, gestures, hearts,
animals, food, sports, objects, symbols, keycaps, the ZWJ sequences, the
flags of every country…) except the skin-tone variants (the game draws an
emoji with a skin tone as its base, in the default yellow), the lone
regional indicator letters and Twitter's private-use pictures.

The atlas: 2048×2048 pixels (powers of two, for mipmaps), cells of CELL
pixels, COLUMNS to a row, in the order of the table; each picture is ART
pixels across in the middle of its cell, with clear pixels around it so the
smaller mipmap levels never mix two pictures. The colours are reduced to a
256-colour palette with pngquant, without dithering (Twemoji's flat colours
lose nothing seen, and dithering would spill into the clear border). The
game spreads the pictures' edge colours into the clear pixels round them
when it loads the atlas. CELL, ART and COLUMNS are also in emoji.rs: change
both together (a test there checks the atlas against them).

The table (emoji.txt), read by crates/client/src/emoji.rs: comment lines
start with '#'; then one line per cell, in atlas order: the code points of
the sequence in hex, joined by '-', WITHOUT U+FE0F (the game skips U+FE0F,
and skin tones, when it matches text against the table). A line ending in
" text" is a single character the game's font draws as text (©, ❤, ☺, ♠…):
it becomes a picture only when U+FE0F (or a skin tone) follows it.
"""
import os
import subprocess
import sys
import tempfile
from multiprocessing import Pool

import regex
from fontTools.ttLib import TTFont
from PIL import Image

CELL, ART, SIDE = 40, 36, 2048
COLUMNS = SIDE // CELL
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(ROOT, "crates/client/assets")
TONES = {0x1F3FB, 0x1F3FC, 0x1F3FD, 0x1F3FE, 0x1F3FF}
REGIONAL = range(0x1F1E6, 0x1F1FF + 1)


def is_emoji(c):
    return bool(regex.match(r"[\p{Emoji}\p{Emoji_Component}]", chr(c)))


def wanted(seq):
    if TONES & set(seq):
        return False
    if len(seq) == 1 and seq[0] in REGIONAL:
        return False
    return all(is_emoji(c) for c in seq)


def render(job):
    svg, png = job
    subprocess.run(["rsvg-convert", "-w", str(ART), "-h", str(ART), "-o", png, svg], check=True)


def main(svg_dir):
    files = {}
    for name in os.listdir(svg_dir):
        if name.endswith(".svg"):
            seq = tuple(int(p, 16) for p in name[:-4].split("-"))
            if wanted(seq):
                key = tuple(c for c in seq if c != 0xFE0F)
                assert key not in files, name
                files[key] = os.path.join(svg_dir, name)
    keys = sorted(files)
    assert len(keys) <= COLUMNS * (SIDE // CELL), "the atlas is full"
    font = TTFont(os.path.join(ASSETS, "DejaVuSans.ttf")).getBestCmap()

    def as_text(key):
        c = key[0]
        return len(key) == 1 and c in font and not regex.match(r"\p{Emoji_Presentation}", chr(c))

    atlas = Image.new("RGBA", (SIDE, SIDE), (0, 0, 0, 0))
    pad = (CELL - ART) // 2
    with tempfile.TemporaryDirectory() as tmp:
        jobs = [(files[k], os.path.join(tmp, f"{i}.png")) for i, k in enumerate(keys)]
        with Pool() as pool:
            pool.map(render, jobs)
        for i, (_, png) in enumerate(jobs):
            x, y = (i % COLUMNS) * CELL + pad, (i // COLUMNS) * CELL + pad
            atlas.paste(Image.open(png).convert("RGBA"), (x, y))
        full = os.path.join(tmp, "atlas.png")
        atlas.save(full)
        out = os.path.join(ASSETS, "emoji.png")
        subprocess.run(
            ["pngquant", "--force", "--speed", "1", "--nofs", "--strip", "--output", out, "256", full],
            check=True,
        )
    lines = [
        "# Generated by tools/gen_emoji.py: do not edit by hand.",
        f"# The cells of emoji.png ({CELL} px, {COLUMNS} to a row, pictures {ART} px across),",
        "# in order: code points in hex without U+FE0F; \"text\": drawn by the font",
        "# unless U+FE0F (or a skin tone) follows.",
    ]
    for k in keys:
        lines.append("-".join(f"{c:x}" for c in k) + (" text" if as_text(k) else ""))
    with open(os.path.join(ASSETS, "emoji.txt"), "w") as f:
        f.write("\n".join(lines) + "\n")
    flags = sum(1 for k in keys if len(k) == 2 and all(c in REGIONAL for c in k))
    size = os.path.getsize(out)
    print(f"{len(keys)} emoji ({flags} flags) -> {out} ({size // 1024} KiB)")


if __name__ == "__main__":
    main(sys.argv[1])
